#!/usr/bin/env python3
"""Assemble maintained Lua release entries into the in-game history."""
from pathlib import Path
import argparse
import json
import os
import re
import tempfile


def generate(root):
    entries = []
    versions = set()
    for path in (root / "patchnote").glob("*.lua"):
        source = path.read_text(encoding="utf-8")
        body = re.sub(r"\A(?:\s*--[^\n]*\n)*\s*return\s+", "", source, count=1).strip()
        if not body.startswith("{") or not body.endswith("}"):
            raise ValueError(f"{path.name}: expected a returned Lua table")
        version = re.search(r'^\s*version\s*=\s*"([^"]+)"\s*,', body, re.M)
        status = re.search(r'^\s*status\s*=\s*"([^"]+)"\s*,', body, re.M)
        if not version or version[1] != path.stem or version[1] in versions:
            raise ValueError(f"{path.name}: missing, duplicate or mismatched version")
        version = version[1]
        expected = "development" if version == "Unreleased" else "released"
        if not status or status[1] != expected:
            raise ValueError(f"{path.name}: expected status {expected}")
        if version != "Unreleased" and not re.fullmatch(r"\d+\.\d+\.\d+", version):
            raise ValueError(f"{path.name}: expected major.minor.patch")
        for category in ("additions", "fixes"):
            if not re.search(rf"^\s*{category}\s*=\s*{{", body, re.M):
                raise ValueError(f"{path.name}: missing {category} list")
        versions.add(version)
        key = (1,) if version == "Unreleased" else (0, *map(int, version.split(".")))
        entries.append((key, body))
    toc = (root / "SkillsAlreadyKnown.toc").read_text()
    current = re.search(r"^## Version:\s*(\S+)", toc, re.M)
    if not current or current[1] not in versions:
        raise ValueError("The TOC version needs its own patchnote entry")
    entries.sort(reverse=True)
    header = ('-- Generated by scripts/generate-patchnotes.py; edit patchnote/*.lua.\n'
              'local SAK = SkillsAlreadyKnown\nif SAK.disabledByDev then\n  return\nend\n\n'
              'SAK.Patchnotes = {\n')
    return header + ''.join('  ' + body.replace('\n', '\n  ') + ',\n' for _, body in entries) + '}\n'


def markdown(root, version=None):
    # Keep one maintained source for both the in-game history and CurseForge.
    generate(root)
    toc = (root / "SkillsAlreadyKnown.toc").read_text()
    version = version or re.search(r"^## Version:\s*(\S+)", toc, re.M)[1]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Markdown requires a released major.minor.patch version")
    source = (root / "patchnote" / (version + ".lua")).read_text()
    title = re.search(r"^## Title:\s*(.+)", toc, re.M)[1]
    lines = [f"# {title} — {version}"]
    decoder = json.JSONDecoder()
    for key, heading in (("additions", "Ajouts de fonctionnalités"), ("fixes", "Corrections de bugs")):
        match = re.search(r"^\s*" + key + r"\s*=\s*\{", source, re.M)
        offset, notes = match.end(), []
        while True:
            whitespace = re.match(r"(?:\s+|--[^\n]*(?:\n|$))*", source[offset:])
            offset += whitespace.end()
            if source[offset:offset + 1] == "}":
                break
            # Notes are plain double-quoted strings, never executable expressions.
            note, consumed = decoder.raw_decode(source[offset:])
            if not isinstance(note, str):
                raise ValueError(f"{key}: expected a quoted note")
            notes.append(note)
            offset += consumed
            offset += re.match(r"\s*", source[offset:]).end()
            if source[offset:offset + 1] == ",":
                offset += 1
            elif source[offset:offset + 1] != "}":
                raise ValueError(f"{key}: expected a comma or closing brace")
        if notes:
            lines.extend(["", "## " + heading, ""])
            lines.extend("- " + note.replace("\n", "\n  ") for note in notes)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--format", choices=("lua", "markdown"), default="lua")
    parser.add_argument("--version", help="Released version for Markdown; defaults to the TOC version")
    args = parser.parse_args()
    default_output = "release/latest/patchnote.md" if args.format == "markdown" else "data/Patchnotes.lua"
    output = args.output or args.root / default_output
    try:
        content = markdown(args.root, args.version) if args.format == "markdown" else generate(args.root)
        if args.check:
            if not output.exists() or output.read_text() != content:
                parser.exit(1, "Patchnotes are stale: run scripts/generate-patchnotes.py\n")
        elif not output.exists() or output.read_text() != content:
            output.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=output.parent, delete=False) as temporary:
                temporary.write(content)
                name = temporary.name
            os.chmod(name, 0o644)
            os.replace(name, output)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Patchnote generation failed: {error}\n")


if __name__ == "__main__":
    main()
